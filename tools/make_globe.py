"""
Generates the data for the 3D dot globe used on the About page.

Writes src/sections/globe.ts with:
  globeDots  - { x, y, z, hot } positions on a unit sphere (percent based)
  globePins  - { id, label, sub, x, y, z } for the achievement countries
"""

import os
import math

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "sections", "globe.ts")

from make_maps import WORLD, INDIA  # reuse the coastline data


def pip(lon, lat, poly):
    inside = False
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i+1) % n]
        if (y1 > lat) != (y2 > lat):
            xin = (x2 - x1) * (lat - y1) / (y2 - y1) + x1
            if lon < xin:
                inside = not inside
    return inside


def on_land(lon, lat):
    for poly in WORLD:
        if pip(lon, lat, poly):
            return True
    return False


def in_india(lon, lat):
    return pip(lon, lat, INDIA)


def to_sphere(lon, lat, radius=1.0):
    """Equirectangular -> unit sphere -> 3D point (y up)."""
    phi = math.radians(lat)
    lam = math.radians(lon)
    x = radius * math.cos(phi) * math.sin(lam)
    y = radius * math.sin(phi)
    z = radius * math.cos(phi) * math.cos(lam)
    return round(x, 4), round(y, 4), round(z, 4)


def build():
    land, shell = [], []

    # land dots on a 3 degree grid
    step = 3.6
    lat = -60.0
    while lat <= 84.0:
        lon = -180.0
        while lon <= 180.0:
            if on_land(lon, lat):
                x, y, z = to_sphere(lon, lat)
                land.append(
                    {"x": x, "y": y, "z": z, "hot": in_india(lon, lat)}
                )
            lon += step
        lat += step

    # faint sphere shell so the globe reads as a solid body
    lat = -80.0
    while lat <= 80.0:
        lon = -180.0
        while lon <= 180.0:
            x, y, z = to_sphere(lon, lat)
            shell.append({"x": x, "y": y, "z": z})
            lon += 11.0
        lat += 11.0

    pins = []
    for pid, label, sub, lon, lat, side, dy in [
        ("serbia", "Serbia", "International circuit", 20.9, 44.0, "left", -14),
        ("kazakhstan", "Kazakhstan", "World-level podiums", 66.9, 48.0, "right", -18),
        ("uzbekistan", "Uzbekistan", "IMGC · gold", 64.5, 41.5, "left", 18),
        ("india", "India", "WKC World Championship", 78.9, 22.0, "right", 16),
    ]:
        x, y, z = to_sphere(lon, lat)
        pins.append(
            {
                "id": pid,
                "label": label,
                "sub": sub,
                "x": x,
                "y": y,
                "z": z,
                "side": side,
                "dy": dy,
            }
        )

    lines = [
        "/**",
        " * Auto-generated by tools/make_globe.py — do not edit by hand.",
        " * 3D dot globe: land dots, a faint sphere shell and the achievement pins.",
        " */",
        "",
        "export type GlobeDot = { x: number; y: number; z: number; hot?: boolean };",
        "",
        "export type GlobePin = {",
        "\tid: string;",
        "\tlabel: string;",
        "\tsub: string;",
        "\tx: number;",
        "\ty: number;",
        "\tz: number;",
        "\tside: \"left\" | \"right\";",
        "\tdy: number;",
        "};",
        "",
        f"export const globeDots: GlobeDot[] = [",
    ]
    for d in land:
        hot = ", hot: true" if d["hot"] else ""
        lines.append(
            f"\t{{ x: {d['x']}, y: {d['y']}, z: {d['z']}{hot} }},"
        )
    lines.append("];")
    lines.append("")
    lines.append("export const globeShell: GlobeDot[] = [")
    for d in shell:
        lines.append(f"\t{{ x: {d['x']}, y: {d['y']}, z: {d['z']} }},")
    lines.append("];")
    lines.append("")
    lines.append("export const globePins: GlobePin[] = [")
    for p in pins:
        lines.append(
            f"\t{{ id: \"{p['id']}\", label: \"{p['label']}\", sub: \"{p['sub']}\","
            f" x: {p['x']}, y: {p['y']}, z: {p['z']},"
            f" side: \"{p['side']}\", dy: {p['dy']} }},"
        )
    lines.append("];")
    lines.append("")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"land dots: {len(land)}  shell: {len(shell)}  pins: {len(pins)}")
    print("written:", OUT)


if __name__ == "__main__":
    build()
